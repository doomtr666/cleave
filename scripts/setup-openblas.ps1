<#
Downloads (or reuses) the prebuilt OpenBLAS toolchain `cleave-openblas-redist`
publishes. Running this with no arguments is normally *all* that's needed --
`cleave-rt` loads `openblas.dll` explicitly at runtime (`LoadLibraryW`, not an
ordinary implicit link -- `cleave-rt/Cargo.toml`'s own doc comment), from a
path baked in at compile time (`<this repo>/target/openblas`, this script's
own default `-CacheDir`) -- no `PATH`/env var/manual DLL copy needed for the
common case, on *any* process (`cleave.exe`, any "-interop" example, even
that example's own build script).

Also merges an `OPENBLAS_PREFIX` entry into `.cargo/config.toml` (gitignored,
machine-specific -- see `scripts/setup-toolchain.ps1`'s own identical
convention for LLVM/MLIR) as an optional *override* for a non-default
install location (`-ExistingPrefix`, below) -- real, but only takes effect
for a process cargo itself spawns (`cargo run`/`cargo test`), since it's an
ordinary process environment variable, not a system-wide one. A standalone
`.exe` run outside cargo, pointed at a non-default OpenBLAS install, needs a
real `OPENBLAS_PREFIX` set some other way (a shell profile, a launch script).

Merges into the existing `[env]` block rather than overwriting it outright --
`setup-toolchain.ps1` may already have written `CLEAVE_LLVM_PREFIX` into the very same file, and both scripts need to
coexist there.

Usage:
  scripts/setup-openblas.ps1                                       # download/cache the pinned release (ci/openblas-version.txt)
  scripts/setup-openblas.ps1 -Force                                # re-download even if the cache already looks current
  scripts/setup-openblas.ps1 -ExistingPrefix I:\openblas-windows   # point at an already-built/extracted local layout instead -- no download
#>
param(
    # Same reasoning as `setup-toolchain.ps1`'s own `$CacheDir` default --
    # `target\` (already gitignored), not `%LOCALAPPDATA%`, so a multi-drive
    # dev setup never has this land on the wrong disk.
    [string]$CacheDir = ([System.IO.Path]::Combine($PSScriptRoot, "..", "target", "openblas")),
    [string]$ExistingPrefix = "",
    [switch]$Force
)

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$cargoConfigPath = [System.IO.Path]::Combine($repoRoot, ".cargo", "config.toml")

function Merge-CleaveCargoConfigEnv([hashtable]$NewEntries) {
    $entries = [ordered]@{}
    if (Test-Path $cargoConfigPath) {
        $inEnv = $false
        foreach ($line in Get-Content $cargoConfigPath) {
            $trimmed = $line.Trim()
            if ($trimmed -eq "[env]") { $inEnv = $true; continue }
            if ($trimmed.StartsWith("[") -and $trimmed -ne "[env]") { $inEnv = $false; continue }
            if ($inEnv -and ($trimmed -match '^([A-Za-z0-9_]+)\s*=\s*"(.*)"$')) {
                $entries[$Matches[1]] = $Matches[2]
            }
        }
    }
    foreach ($key in $NewEntries.Keys) {
        $entries[$key] = $NewEntries[$key]
    }
    New-Item -ItemType Directory -Force -Path (Split-Path $cargoConfigPath) | Out-Null
    $lines = @(
        "# Generated by scripts/setup-toolchain.ps1 / scripts/setup-openblas.ps1 --",
        "# gitignored, machine-specific, safe to delete and regenerate. Do not",
        "# hand-edit or commit (see .cargo/config.toml.example). Re-run the",
        "# relevant script after a toolchain/OpenBLAS version bump to refresh it.",
        "[env]"
    )
    foreach ($key in $entries.Keys) {
        $lines += "$key = `"$($entries[$key])`""
    }
    # UTF-8 without a BOM, from Windows PowerShell 5.1 (whose `-Encoding utf8`
    # writes one) as from `pwsh`.
    [System.IO.File]::WriteAllText($cargoConfigPath, ($lines -join "`n") + "`n", (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Wrote $cargoConfigPath"
}

function Write-OpenblasPrefix([string]$Prefix) {
    $forward = $Prefix -replace '\\', '/'
    Merge-CleaveCargoConfigEnv @{ "OPENBLAS_PREFIX" = $forward }
    Write-Host "OPENBLAS_PREFIX -> $Prefix (only needed as an override -- see this script's own top comment)"
}

# Windows PowerShell 5.1 has no `$IsWindows`; `pwsh` on Linux runs this too.
$onWindows = ([System.Environment]::OSVersion.Platform -eq [System.PlatformID]::Win32NT)
# The file `cleave-rt` loads (`blas_dynload`), relative to the prefix.
$library = if ($onWindows) { "bin/openblas.dll" } else { "lib/libopenblas.so" }

if ($ExistingPrefix -ne "") {
    $probe = Join-Path $ExistingPrefix $library
    if (-not (Test-Path $probe)) {
        throw "-ExistingPrefix '$ExistingPrefix' doesn't look like a real OpenBLAS install (no $library under it)"
    }
    Write-OpenblasPrefix $ExistingPrefix
} else {

    $tagFile = [System.IO.Path]::Combine($repoRoot, "ci", "openblas-version.txt")
    $tag = (Get-Content $tagFile | Select-Object -First 1).Trim()
    # cleave-openblas-redist's assets: the prefix's contents at the root of
    # the Windows zip, under `openblas-linux-x86_64/` in the Linux tarball.
    $asset = if ($onWindows) { "openblas-windows-msvc.zip" } else { "openblas-linux-x86_64.tar.gz" }
    $url = "https://github.com/doomtr666/cleave-openblas-redist/releases/download/$tag/$asset"
    $marker = Join-Path $CacheDir ".cleave-openblas-version"

    $upToDate = $false
    if ((-not $Force) -and (Test-Path $marker)) {
        $existingTag = (Get-Content $marker | Select-Object -First 1).Trim()
        if ($existingTag -eq $tag) {
            $upToDate = $true
        }
    }

    if ($upToDate) {
        Write-Host "cleave OpenBLAS $tag already cached at $CacheDir"
    } else {
        Write-Host "Downloading cleave OpenBLAS $tag ($asset)..."
        New-Item -ItemType Directory -Force -Path $CacheDir | Out-Null
        Get-ChildItem -Path $CacheDir -Force | Remove-Item -Recurse -Force -ErrorAction SilentlyContinue
        $archive = Join-Path ([System.IO.Path]::GetTempPath()) $asset
        Invoke-WebRequest -Uri $url -OutFile $archive -UseBasicParsing
        if ($onWindows) {
            Expand-Archive -Path $archive -DestinationPath $CacheDir -Force
        } else {
            # `tar` keeps `libopenblas.so`'s symlinks; its top directory dropped.
            & tar -xzf $archive -C $CacheDir --strip-components=1
            if ($LASTEXITCODE -ne 0) { throw "tar failed to extract $archive" }
        }
        Remove-Item $archive -Force
        Set-Content -Path $marker -Value $tag
        Write-Host "Installed cleave OpenBLAS $tag to $CacheDir"
    }

    Write-OpenblasPrefix $CacheDir
}
